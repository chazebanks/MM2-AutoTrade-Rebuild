local F=dofile("pdiddler/tests/integration_fixture.lua")
local path=arg[1] or "pdiddler/pdiddler_FASTGATE_V5_INTEGRATED_TEST_v3.lua"
local passed,failed=0,0
local function test(name,fn)
    local ok,err=pcall(fn)
    if ok then passed=passed+1; print("PASS "..name)
    else failed=failed+1; print("FAIL "..name..": "..tostring(err)) end
end
local function run(o,t) local f=F.new(o); f:run(path); f:advance(t or 20); return f end
local function eq(a,b) assert(a==b,tostring(a).." ~= "..tostring(b)) end
test("tablet then nil-returning gate then scanner/P4/outgoing",function()
    local f=run(); eq(f:count("outgoing"),1); eq(#f.errors,0)
    local times={}; for _,e in ipairs(f.events) do times[e.name]=e.at end
    assert(times.p2<times.gate and times.gate+10<=times.scanner and times.scanner<times.p4 and times.p4<=times.outgoing)
end)
test("correct Container request path permits exhaustion hop",function() local f=run(nil,60); eq(f:count("hop"),1) end)
test("exhausted hop quiesces outgoing and P4 before transport",function()
    local f=run(nil,60); eq(f:count("hop"),1); assert(f.outStopped and f.p4Stopped)
end)
test("corroborated bot rejects before starting scanner",function()
    local f=run({gateState="BOT_PATTERN_FOR_REVIEW"},20); eq(f:count("hop"),1); eq(f:count("scanner"),0)
end)
for _,state in ipairs({"ANIMATION_CLUSTER_FOR_REVIEW","HIGH_SUSPICION_CLUSTER","LOW_COVERAGE_CLUSTER_FOR_REVIEW"}) do
    test(state.." permits trading without bot hop",function() local f=run({gateState=state}); eq(f:count("outgoing"),1); eq(f:count("hop"),0) end)
end
test("low appearance score cannot reject",function() local f=run({gateState="BOT_PATTERN_FOR_REVIEW",score=0}); eq(f:count("hop"),0); eq(f:count("outgoing"),1) end)
test("gate timeout proceeds unverified",function() local f=run({gateTimeout=true},25); eq(f:count("outgoing"),1); eq(f.controller.lastDecision,"PROCEED_UNVERIFIED") end)
test("wrong job result never rejects",function() local f=run({wrongJob=true,gateState="BOT_PATTERN_FOR_REVIEW"},25); eq(f:count("hop"),0); eq(f:count("outgoing"),1) end)
test("superseding generation is rejected",function() local f=run({supersede=true,gateState="BOT_PATTERN_FOR_REVIEW"},25); eq(f:count("hop"),0); eq(f:count("outgoing"),1) end)
test("gate ten seconds begins after download",function()
    local f=run({fetchDelay=6,gateState="BOT_PATTERN_FOR_REVIEW"},60)
    eq(f.controller.lastDecision,"BOT_PATTERN_FOR_REVIEW"); eq(f:count("hop"),1); eq(f:count("outgoing"),0)
end)
test("compile error is terminal and releases clean lock",function()
    local f=run({compileFail="pdiddler2_KNOWN_GOOD.lua"}); eq(f.controller.stage,"ERROR"); eq(f.controller.running,false); eq(#f.errors,0)
end)
test("bounded tablet startup",function() local f=run({p2Delay=100},50); eq(f.controller.stage,"ERROR"); eq(f:count("gate"),0); f:advance(110); eq(f:count("gate"),0) end)
test("blocked HTTP has bounded fetch-only retries",function() local f=run({fetchFail="pdiddler2_KNOWN_GOOD.lua"},35); eq(f.controller.stage,"ERROR"); assert(#f.fetches<=2); eq(f:count("p2"),0) end)
test("scanner yields legitimately before exposing API",function() local f=run({scannerDelay=40},70); eq(f:count("outgoing"),1); eq(f.scannerLoads,1) end)
test("scanner timeout locks partial initialization against reruns",function()
    local f=run({scannerDelay=1000},310); eq(f.controller.stage,"ERROR"); f:run(path); f:advance(320); eq(f:count("scanner"),1); eq(f:count("outgoing"),0)
end)
test("outgoing failure stops P4 and prevents unsafe retry",function()
    local f=run({outError=true}); eq(f.controller.stage,"ERROR"); assert(f.p4Stopped); f:run(path); f:advance(30); eq(f:count("scanner"),1)
end)
test("active trade blocks bot rejection",function()
    local f=F.new({gateState="BOT_PATTERN_FOR_REVIEW"}); f.nodes.Trade.Visible=true; f:run(path); f:advance(60); eq(f:count("hop"),0)
end)
test("pending request blocks bot rejection",function()
    local f=F.new({gateState="BOT_PATTERN_FOR_REVIEW"}); f.nodes.SendingRequest.Visible=true; f:run(path); f:advance(60); eq(f:count("hop"),0)
end)
test("desktop tablet request layout permits corroborated bot hop",function()
    local f=F.new({gateState="BOT_PATTERN_FOR_REVIEW"}); f:desktopUi(); f:run(path); f:advance(25)
    eq(f:count("hop"),1); eq(f:count("scanner"),0)
end)
test("desktop tablet request layout supports exhaustion",function()
    local f=F.new(); f:desktopUi(); f:run(path); f:advance(60); eq(f:count("hop"),1)
end)
