    local f=run(nil,40); local p=f:addPlayer(2,"whitelist"); f.white={p}; f:advance(42); f.out.state.processed[2]=true
    f:advance(80); eq(f:count("hop"),0); f:advance(90); eq(f:count("hop"),1)
end)
