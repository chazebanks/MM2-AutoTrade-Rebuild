test("eligible trader processed inside final recheck resets full window",function()
    local f=run(nil,55)
    f.task.delay(1,function() local p=f:addPlayer(2,"whitelist"); f.white={p} end)
    f.task.delay(1.5,function() f.out.state.processed[2]=true end)
    f:advance(80); eq(f:count("hop"),0); f:advance(105); eq(f:count("hop"),1)
end)
