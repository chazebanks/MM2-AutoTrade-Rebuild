local count=0
local function test(name,fn) fn();count=count+1;print("PASS "..name) end
test("two positive complete scans retain existing bot classification at ten seconds",function()
 local f=gateFixture():start();f:advance(9.8);assert(not f:result());f:advance(10.1)
 assert(f:result().state=="BOT_PATTERN_FOR_REVIEW");assert(f:result().elapsed<=10.1)
end)
test("diverse older avatars do not become positive bot evidence",function()
 local f=gateFixture({diverse=true}):start();f:advance(10.1);assert(f:result().state=="PROCEED_UNVERIFIED")
end)
test("unreadable required avatar fields cannot form a valid shared fingerprint",function()
 local f=gateFixture({badDescription=true}):start();f:advance(10.1)
 assert(f:result().state~="BOT_PATTERN_FOR_REVIEW","partial appearance read counted as bot evidence")
end)
test("hung appearance fetch cannot delay the ten-second watchdog",function()
 local f=gateFixture({hung=true}):start();f:advance(10.1)
 assert(f:result().state=="PROCEED_UNVERIFIED");assert(f:result().elapsed<=10.1)
 f:advance(110);assert(f:result().state=="PROCEED_UNVERIFIED")
end)
test("stopped generation cannot publish a delayed result",function()
 local f=gateFixture({hung=true}):start();f:advance(1);f.env.PDIDDLER_FAST_GATE_GEN=f.env.PDIDDLER_FAST_GATE_GEN+1
 f:advance(110);assert(not f:result())
end)
test("positive scans from an old roster cannot reject the final roster",function()
 local f=gateFixture():start();f:advance(7);f.players[1].UserId=99;f:advance(10.1)
 assert(f:result().state~="BOT_PATTERN_FOR_REVIEW")
end)
test("finished watchdog fences remaining description work",function()
 local f=gateFixture({hung=true}):start();f:advance(10.1);local reads=f.reads;f:advance(110)
 assert(f.reads==reads,"stale scan continued reading players")
 assert(f:result().generation==f.env.PDIDDLER_FAST_GATE_GEN)
 assert(f:result().evidenceVersion==6 and f:result().roster)
end)
test("movement in two windows is not missing-animation evidence in two windows",function()
 local f=gateFixture():start();f:advance(.1)
 for i=1,4 do local p=f.players[i];f.measurementRows[p.UserId]={player=p,char=p.Character,
  still=0,teleports=0,bad=0,moving=7,absence=6,present=1,early=6,late=1,earlyAbsent=6,lateAbsent=0} end
 local m=f.readOverview();assert(m.absent==0 and m.oneWindow==4 and m.tracked==4)
end)
print("TOTAL "..count.." actual fast-gate runtime tests")
