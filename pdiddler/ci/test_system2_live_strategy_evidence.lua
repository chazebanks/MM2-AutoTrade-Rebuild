local E=dofile("pdiddler/system2/system2_live_strategy_evidence.lua")
local passed=0
local function it(slot,name,qty,chroma)
 return {slot=slot,name=name,id=name,qty=qty or 1,chroma=chroma==true}
end
local function same(a,b,why)if a~=b then error((why or "mismatch")..":"..tostring(a).." != "..tostring(b)) end end
local function test(name,fn)
 local ok,msg=pcall(fn);if not ok then error(name..": "..tostring(msg))end
 passed=passed+1;print("PASS "..name)
end
local A={it(1,"OwnA")};local AA={it(1,"OwnA"),it(2,"OwnB")}
local B={it(1,"OfferA")};local C={it(1,"OfferB",2,true)}
test("actual event produces privacy-safe local evidence not real bot delivery",function()
 local r=E.review("EVENT_PROVENANCE",{},B,nil)
 same(r.status,"CLIENT_RESEARCH_EVIDENCE")
 same(r.localEventKind,"CLIENT_ALT_OFFER_OBSERVED")
 same(r.v2BotAcknowledgementProven,false)
 same(r.mayUseForStrategyLearning,false)
 same(r.realDiscordV2Delivered,false)
end)
test("real changed offer invalidates candidate but not infer player greed",function()
 local r=E.review("BEHAVIOR_REVISION",{},B,C)
 same(r.status,"CLIENT_RESEARCH_EVIDENCE")
 same(r.firstResearchCandidateInvalidated,true)
 same(r.counterpartyPreferenceProven,false)
 same(r.greedyOrValueWatcherLabelInferred,false)
 same(r.clientRevisionKind,"DIFFERENT_CLIENT_ITEM_CANDIDATE")
end)
test("bilateral alternatives modeled, no fictitious economic ranking",function()
 local r=E.review("BILATERAL_ALTERNATIVES",A,B,C)
 same(r.bilateralClientAlternativeCount,2)
 same(r.outgoingPhysicalSlots,1)
 same(r.firstIncomingCopies,1)
 same(r.secondIncomingCopies,2)
 same(r.currentMarketSourceVerified,false)
 same(r.profitBasedWinnerProven,false)
 same(r.recommendedOfferIndex,nil)
end)
test("two distinct structural growth shapes, no future seller invented",function()
 local r=E.review("GROWTH_STRUCTURE",AA,B,nil)
 same(r.distinctStructuralPathOptions,2)
 same(r.pathA.hypotheticalOwnPhysicalSlots,2)
 same(r.pathB.hypotheticalOwnPhysicalSlots,1)
 same(r.futureSellerCounterpartiesInvented,false)
 same(r.currentTargetGapCalculable,false)
end)
test("one physical slot can contain five copies",function()
 local r=E.review("GROWTH_STRUCTURE",AA,{it(1,"StackA",5)},nil)
 same(r.status,"CLIENT_RESEARCH_EVIDENCE")
end)
test("fabricated fifth slot never passes validation",function()
 local x={}
 for i=1,5 do x[i]=it(i,"Bad"..i) end
 local r=E.review("GROWTH_STRUCTURE",AA,x,nil)
 same(r.status,"BLOCKED")
end)
test("protected target never outbound even if an item is labeled differently",function()
 local r=E.review("BILATERAL_ALTERNATIVES",
  {it(1,"Ginger Scope",1)},B,C)
 same(r.status,"BLOCKED")
 same(r.reason,"PROTECTED_GINGERSCOPE_NEVER_OUTBOUND")
end)
test("same visible proposal does not count as revision",function()
 local r=E.review("INVALIDATE_STALE_RESEARCH",{},B,B)
 same(r.status,"BLOCKED")
 same(r.reason,"UNCONFIRMED_DISTINCT_LIVE_REVISION")
end)
test("quantity-only variant is recognized without invented client identity",function()
 local r=E.review("BEHAVIOR_REVISION",{},B,{it(1,"OfferA",2)})
 same(r.clientRevisionKind,"STACK_QUANTITY_CHANGED")
 same(r.verifiedSellerWillingness,false)
 same(r.serverSettlementProven,false)
end)
test("malformed and contaminated physical offers fail closed",function()
 local x={it(1,"A")}
 x.rawInjected=it(1,"B")
 same(E.review("EVENT_PROVENANCE",{},x,nil).status,"BLOCKED")
 same(E.review("GROWTH_STRUCTURE",{},B,nil).status,"BLOCKED")
end)
print("SYSTEM2_LIVE_STRATEGY_INTERPRETER_SOURCE_TEST_PASS "..tostring(passed).." groups")
