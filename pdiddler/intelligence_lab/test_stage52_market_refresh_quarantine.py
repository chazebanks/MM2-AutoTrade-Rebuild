"""Stage52: quarantine scheduled market refresh; test the REAL updater.

All tests are network-free, run in the existing Python intelligence CI,
and verify neither a clock stamp nor minimum row counts can certify prices.
"""
from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import importlib.util
import json
from pathlib import Path
import random
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts/update_values.py"
WORKFLOW = ROOT / ".github/workflows/refresh-values.yml"
LIVE = ROOT / "values/mm2values.lua"
STAGE26 = ROOT / "pdiddler/snapshots/supreme_snapshot_2026_11_06.json"
spec = importlib.util.spec_from_file_location("stage52_actual_market_updater", SCRIPT)
assert spec and spec.loader
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)


def groups():
    mapping = {
        "Godly": {f"Godly_{i:03d}": i+1 for i in range(100)},
        "Ancient": {f"Ancient_{i:03d}": 100+i for i in range(16)},
        "Chroma": {f"Chroma Item_{i:03d}": 200+i for i in range(40)},
    }
    mapping["Ancient"]["Gingerscope"] = mapping["Ancient"].pop("Ancient_000")
    out = {}
    for kind in audit.KIND_ORDER:
        rows = mapping[kind]
        raw_html=("<html><body><h1>" + kind +
                  "</h1><p>synthetic offline fixture only</p></body></html>").encode()
        out[kind] = {
            "kind": kind, "url": audit.ROOT+kind.lower(),
            "retrievedAtUtc": "2026-11-07T22:00:00Z",
            "sourceHtml": raw_html,
            "sha256": hashlib.sha256(raw_html).hexdigest(),
            "rowCount": len(rows), "rows": dict(rows),
            "publisherUpdatedAtUtc": None,
        }
    return out


def sample_baseline(path: Path):
    path.write_text(
        "-- GENERATED by scripts/update_values.py; do not edit manually.\n"
        "-- Primary source: https://mm2values.com/ (Godly, Ancient, Chromas)\n"
        'local M = {source = "https://mm2values.com/", updated = "2026-11-02", complete = true, items = {\n'
        '  ["Gingerscope"] = {value = 15250, category = "Ancient"},\n'
        '  ["OldName"] = {value = 23, category = "Godly"},\n'
        '  ["Godly_003"] = {value = 4, category = "Godly"},\n'
        '}}\nfunction M.get(name) return M.items[name] end\nreturn M\n',
        encoding="utf-8",
    )


class Stage52QuarantinedRefreshTests(unittest.TestCase):
    def test_actual_checked_in_legacy_baseline_is_only_retrieval_metadata(self):
        old, date = audit.read_baseline(LIVE)
        self.assertGreater(len(old), 150)
        self.assertIsNotNone(date)
        self.assertEqual(len(old), len(set(old)))
        self.assertIn("Gingerscope", old)
        self.assertEqual(old["Gingerscope"][1], "Ancient")

    def test_original_stage26_supreme_source_is_expired(self):
        blob = json.loads(STAGE26.read_text(encoding="utf-8"))
        expires = datetime.fromisoformat(blob["expiresAt"].replace("Z", "+00:00"))
        self.assertLess(expires, datetime.now(timezone.utc))
        self.assertNotEqual(blob["publishedAt"], blob["observedAt"])
        self.assertEqual(blob["coverage"]["total"], 190)
        self.assertNotIn("newValuePublishedNow", blob)

    def test_scheduled_workflow_cannot_push_market_values(self):
        s = WORKFLOW.read_text(encoding="utf-8")
        self.assertIn("contents: read", s)
        self.assertNotIn("contents: write", s)
        self.assertNotIn("git push", s)
        self.assertNotIn("git add values/mm2values.lua", s)
        self.assertIn("python scripts/update_values.py --audit-only", s)
        self.assertIn("actions/upload-artifact@v4", s)
        self.assertIn("mm2_market_refresh/*", s)
        self.assertIn("candidate", s.lower())

    def test_updater_has_no_publish_mode_or_write_to_value_file(self):
        s = SCRIPT.read_text(encoding="utf-8")
        self.assertNotIn('path.write_text("\\n".join(lines)', s)
        self.assertNotIn("git push", s)
        self.assertNotIn("strftime(\"%Y-%m-%d\")", s)
        self.assertNotIn("complete = true", s)
        self.assertIn('"publisherUpdatedAtUtc": None', s)
        self.assertIn('"sourceHtml": raw', s)
        self.assertIn('"source-page-hash-mismatch"', s)
        self.assertIn('"canPublishPrices": False', s)
        self.assertIn('"liveReady": False', s)
        self.assertIn('source-tier-count-disagrees', s)

    def test_unreviewed_pages_always_report_unknown_publisher_time(self):
        report, candidate = audit.build_report(
            groups(), {"Gingerscope": (15250, "Ancient")}, "2026-11-02",
            "2026-11-07T22:00:03Z",
        )
        self.assertIsNone(report["publisherUpdatedAtUtc"])
        self.assertFalse(report["fullCatalogueCompletenessVerified"])
        self.assertFalse(report["independentlyVerifiedPublisherDate"])
        self.assertFalse(report["canPublishPrices"])
        self.assertFalse(report["liveReady"])
        self.assertFalse(candidate["canPublishPrices"])
        self.assertFalse(candidate["authorizesAccept"])
        self.assertFalse(report["authorizesTrade"])
        self.assertEqual(report["sourcePages"]["Godly"]["publisherUpdatedAtUtc"], None)
        self.assertTrue(report["diff"]["hasDisagreement"])
        changed = report["diff"]["changed"]
        self.assertEqual(len(changed), 1)
        self.assertEqual(changed[0]["name"], "Gingerscope")

    def test_new_retrieval_day_cannot_claim_new_publisher_update(self):
        original_pages = groups()
        identical_values = audit.normalize_page_results(original_pages)
        first, _ = audit.build_report(
            original_pages, identical_values, "2026-11-06",
            "2026-11-06T18:53:21Z",
        )
        second_pages = groups()
        for page in second_pages.values():
            page["retrievedAtUtc"] = "2026-11-07T18:53:21Z"
        second, _ = audit.build_report(
            second_pages, identical_values, "2026-11-07",
            "2026-11-07T18:53:21Z",
        )
        self.assertNotEqual(first["auditedAtUtc"], second["auditedAtUtc"])
        self.assertIsNone(first["publisherUpdatedAtUtc"])
        self.assertIsNone(second["publisherUpdatedAtUtc"])
        self.assertFalse(first["diff"]["hasDisagreement"])
        self.assertFalse(second["diff"]["hasDisagreement"])
        self.assertFalse(first["canPublishPrices"])
        self.assertFalse(second["canPublishPrices"])

    def test_main_audit_writes_only_quarantine_and_leaves_live_file_identical(self):
        with tempfile.TemporaryDirectory(prefix="stage52_") as tmp:
            target = Path(tmp)
            baseline = target / "mm2values.lua"
            sample_baseline(baseline)
            before = hashlib.sha256(baseline.read_bytes()).hexdigest()
            output = target / "candidate"
            g = groups()
            with patch.object(audit, "collect", side_effect=lambda kind: g[kind]):
                status = audit.main([
                    "--audit-only", "--output-dir", str(output),
                    "--baseline", str(baseline),
                ])
            self.assertEqual(status, 0)
            self.assertEqual(hashlib.sha256(baseline.read_bytes()).hexdigest(), before)
            self.assertEqual(
                {p.name for p in output.iterdir()},
                {"source_audit.json", "candidate_NOT_FOR_TRADING.json",
                 "source_godly.html", "source_ancient.html", "source_chroma.html"},
            )
            result = json.loads((output / "source_audit.json").read_text())
            proposed = json.loads((output / "candidate_NOT_FOR_TRADING.json").read_text())
            self.assertIsNone(result["publisherUpdatedAtUtc"])
            self.assertFalse(proposed["canPublishPrices"])
            for kind in audit.KIND_ORDER:
                captured = output / result["sourcePages"][kind]["archivedHtml"]
                self.assertEqual(
                    hashlib.sha256(captured.read_bytes()).hexdigest(),
                    result["sourcePages"][kind]["sha256"],
                )
            self.assertEqual(result["baselineGeneratedDateUnverified"], "2026-11-02")
            self.assertEqual(proposed["rowCount"], 156)
            self.assertEqual(result["diff"]["changed"][0]["name"], "Gingerscope")

    def test_failed_page_fetch_creates_no_candidate_files_or_live_update(self):
        with tempfile.TemporaryDirectory(prefix="stage52_failure_") as tmp:
            root = Path(tmp);baseline=root/"mm2values.lua"
            sample_baseline(baseline)
            before=baseline.read_bytes()
            output=root/"quarantine"
            g=groups()
            def fetch(kind):
                if kind == "Ancient":
                    raise RuntimeError("SOURCE_PAGE_UNAVAILABLE")
                return g[kind]
            with patch.object(audit, "collect", side_effect=fetch):
                with self.assertRaisesRegex(RuntimeError, "SOURCE_PAGE_UNAVAILABLE"):
                    audit.main(["--output-dir",str(output),"--baseline",str(baseline)])
            self.assertFalse(output.exists())
            self.assertEqual(baseline.read_bytes(),before)

    def test_rejects_partial_minimum_count_and_garbage_hash(self):
        g=groups();g["Godly"]["rows"].pop("Godly_000")
        g["Godly"]["rowCount"]-=1
        with self.assertRaisesRegex(RuntimeError, "source-tier-coverage-incomplete"):
            audit.normalize_page_results(g)
        g=groups();g["Chroma"]["sha256"]="not-a-real-sha"
        with self.assertRaisesRegex(RuntimeError, "source-page-hash-unverified"):
            audit.normalize_page_results(g)

    def test_valid_looking_but_false_original_source_digest_rejected(self):
        g=groups();g["Godly"]["sha256"]="0"*64
        with self.assertRaisesRegex(RuntimeError, "source-page-hash-mismatch"):
            audit.normalize_page_results(g)
        g=groups();del g["Godly"]["sourceHtml"]
        with self.assertRaisesRegex(RuntimeError, "source-html-unavailable-or-oversize"):
            audit.normalize_page_results(g)

    def test_rejects_fabricated_publisher_dates_and_wrong_url(self):
        g=groups();g["Godly"]["publisherUpdatedAtUtc"]="2026-11-07T22:00:00Z"
        with self.assertRaisesRegex(RuntimeError, "unsupported-unverified-publisher-date"):
            audit.normalize_page_results(g)
        g=groups();g["Godly"]["url"]="https://attacker.invalid"
        with self.assertRaisesRegex(RuntimeError, "source-tier-url-mismatch"):
            audit.normalize_page_results(g)

    def test_rejects_cross_tier_case_alias_and_duplicate_variant(self):
        g=groups();g["Ancient"]["rows"]["godly_001"]=34
        g["Ancient"]["rowCount"]+=1
        with self.assertRaisesRegex(RuntimeError, "case-alias"):
            audit.normalize_page_results(g)
        g=groups();g["Chroma"]["rows"]["UnmarkedChroma"]=1
        g["Chroma"]["rowCount"]+=1
        with self.assertRaisesRegex(RuntimeError, "source-variant-missing"):
            audit.normalize_page_results(g)

    def test_rejects_invalid_price_and_boolean_not_number(self):
        for invalid in (True,0,-1,1.5,2_000_000_000,None):
            g=groups();g["Ancient"]["rows"]["Gingerscope"]=invalid
            with self.subTest(invalid=invalid):
                with self.assertRaisesRegex(RuntimeError, "source-row-invalid"):
                    audit.normalize_page_results(g)

    def test_rejects_missing_tier_and_mismatched_row_count(self):
        g=groups();del g["Chroma"]
        with self.assertRaisesRegex(RuntimeError, "tier-pages-incomplete"):
            audit.normalize_page_results(g)
        g=groups();g["Ancient"]["rowCount"]=999
        with self.assertRaisesRegex(RuntimeError, "source-tier-count-disagrees"):
            audit.normalize_page_results(g)

    def test_baseline_refuses_duplicate_untrusted_existing_lines(self):
        with tempfile.TemporaryDirectory() as td:
            file=Path(td)/"mm2values.lua"
            sample_baseline(file)
            contents=file.read_text()
            contents=contents.replace(
                '  ["OldName"] = {value = 23, category = "Godly"},',
                '  ["OldName"] = {value = 23, category = "Godly"},\n'
                '  ["OldName"] = {value = 8, category = "Godly"},',
            )
            file.write_text(contents)
            with self.assertRaisesRegex(RuntimeError,"baseline-duplicate-or-invalid"):
                audit.read_baseline(file)

    def test_700_seeded_exact_diff_cases_never_authorize_publication(self):
        rng=random.Random(521107)
        for case in range(700):
            count=rng.randint(1,20)
            original={f"Asset_{i}": (rng.randint(1,10000),"Godly") for i in range(count)}
            proposed=dict(original)
            changed=rng.sample(list(proposed), rng.randint(0,count))
            for key in changed:
                val,cat=proposed[key];proposed[key]=(val+1,cat)
            removed=rng.sample(list(proposed), rng.randint(0,count))
            for key in removed:
                del proposed[key]
            added={f"New_{case}_{i}":(i+1,"Godly") for i in range(rng.randint(0,5))}
            proposed.update(added)
            diff=audit.calculate_diff(original,proposed)
            with self.subTest(case=case):
                self.assertEqual(
                    len(diff["added"])+len(diff["removed"])+
                    len(diff["changed"])+diff["unchangedRows"],
                    len(set(original)|set(proposed)),
                )
                self.assertEqual(diff["previousRows"],len(original))
                self.assertEqual(diff["candidateRows"],len(proposed))
                self.assertEqual(
                    diff["hasDisagreement"],
                    bool(diff["changed"] or diff["added"] or diff["removed"]),
                )


