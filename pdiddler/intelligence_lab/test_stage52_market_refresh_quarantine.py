    def test_main_audit_writes_only_quarantine_and_leaves_live_file_identical(self):
        with tempfile.TemporaryDirectory(prefix="stage52_") as tmp:
            target = Path(tmp)
            baseline = target / "mm2values.lua"
            sample_baseline(baseline)
            before = hashlib.sha256(baseline.read_bytes()).hexdigest()
            output = target / "candidate"
            g = groups()
            with patch.object(audit, "collect", side_effect=lambda kind: g[kind]):
                status = audit.main([
                    "--audit-only", "--output-dir", str(output),
                    "--baseline", str(baseline),
                ])
            self.assertEqual(status, 0)
            self.assertEqual(hashlib.sha256(baseline.read_bytes()).hexdigest(), before)
            self.assertEqual(
                {p.name for p in output.iterdir()},
                {"source_audit.json", "candidate_NOT_FOR_TRADING.json",
                 "source_godly.html", "source_ancient.html", "source_chroma.html"},
            )
            result = json.loads((output / "source_audit.json").read_text())
            proposed = json.loads((output / "candidate_NOT_FOR_TRADING.json").read_text())
            self.assertIsNone(result["publisherUpdatedAtUtc"])
            self.assertFalse(proposed["canPublishPrices"])
            for kind in audit.KIND_ORDER:
                captured = output / result["sourcePages"][kind]["archivedHtml"]
                self.assertEqual(
                    hashlib.sha256(captured.read_bytes()).hexdigest(),
                    result["sourcePages"][kind]["sha256"],
                )
            self.assertEqual(result["baselineGeneratedDateUnverified"], "2026-11-02")
            self.assertEqual(proposed["rowCount"], 156)
            self.assertEqual(result["diff"]["changed"][0]["name"], "Gingerscope")

    def test_publish_guard_classifies_same_identity_and_bounded_price_movements(self):
        g=groups()
        original=audit.normalize_page_results(g)
        base, _ = audit.build_report(g, original, "2026-11-06", "2026-11-07T22:00:01Z")
        self.assertEqual(audit.publish_eligibility(base),
                         (True,"STABLE_IDENTITIES_AND_BOUNDED_CHANGES"))
        now=dict(original)
        now["Gingerscope"]=(120,"Ancient")  # fixture old price=100
        fake={"diff":audit.calculate_diff(original,now)}
        self.assertEqual(audit.publish_eligibility(fake)[0],True)
        now["Gingerscope"]=(100000,"Ancient")
        self.assertEqual(audit.publish_eligibility({"diff":audit.calculate_diff(original,now)}),
                         (False,"price-jump-requires-independent-review"))
        now=dict(original);now["Gingerscope"]=(100,"Godly")
        self.assertEqual(audit.publish_eligibility({"diff":audit.calculate_diff(original,now)}),
                         (False,"item-category-or-variant-changed"))
        now=dict(original);now["NewWeapon"]=(1,"Ancient")
        self.assertEqual(audit.publish_eligibility({"diff":audit.calculate_diff(original,now)}),
                         (False,"catalogue-added-or-removed-items-review-required"))

    def test_publish_research_migrates_complete_legacy_file_only_once(self):
        with tempfile.TemporaryDirectory(prefix="stage52_publish_") as td:
            root=Path(td);out=root/"audit";baseline=root/"mm2values.lua"
            fixture=groups();source=audit.normalize_page_results(fixture)
            lines=[
                "-- GENERATED by scripts/update_values.py; do not edit manually.",
                'local M={source="https://mm2values.com/",updated="2026-11-06",complete=true,items={',
            ]
            for name,(value,category) in sorted(source.items()):
                lines.append(
                    '  ["'+name+'"] = {value = '+str(value)+', category = "'+category+'"},')
            lines+=["}}","function M.get(name)return M.items[name] end","return M",""]
            baseline.write_text("\n".join(lines),encoding="utf-8")
            with patch.object(audit,"collect",side_effect=lambda kind:fixture[kind]):
                status=audit.main(["--publish-research-only","--baseline",str(baseline),
                                   "--output-dir",str(out)])
            self.assertEqual(status,0)
            current=baseline.read_text()
            self.assertIn('updated = "PUBLISHER_DATE_UNKNOWN"',current)
            for field in ('complete = false','liveReady = false','authorizesTrade = false',
                          'authorizesAccept = false','mayReportProfit = false',
                          'publisherUpdatedAtUtc = nil'):
                self.assertIn(field,current)
            self.assertNotIn('complete = true',current)
            self.assertIn('sourceSha256 = {',current)
            parsed, stamp = audit.read_baseline(baseline)
            self.assertEqual(parsed,source)
            self.assertEqual(stamp,"PUBLISHER_DATE_UNKNOWN")
            self.assertEqual(len(parsed),156)
            self.assertEqual(len(list(out.iterdir())),5)
            first=baseline.read_bytes()
            # A second HTTP retrieval on the next day is NOT a new publisher update
            # and must not rewrite the same source-value file just to advance its date.
            with patch.object(audit,"collect",side_effect=lambda kind:fixture[kind]),\
                 patch.object(audit,"now_iso",return_value="2026-11-08T18:15:00Z"):
                again=audit.main(["--publish-research-only","--baseline",str(baseline),
                                  "--output-dir",str(out)])
            self.assertEqual(again,0)
            self.assertEqual(baseline.read_bytes(),first)
            # A real bounded value change MAY be observed, but never creates
            # authenticated prices or a false publisher timestamp.
            fixture["Ancient"]["rows"]["Gingerscope"] += 15
            with patch.object(audit,"collect",side_effect=lambda kind:fixture[kind]):
                later=audit.main(["--publish-research-only","--baseline",str(baseline),
                                  "--output-dir",str(out)])
            self.assertEqual(later,0)
            changed,stamp=audit.read_baseline(baseline)
            self.assertEqual(changed["Gingerscope"],(source["Gingerscope"][0]+15,"Ancient"))
            self.assertEqual(stamp,"PUBLISHER_DATE_UNKNOWN")
            self.assertIn('authorizesTrade = false',baseline.read_text())

