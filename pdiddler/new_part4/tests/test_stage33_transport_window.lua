-- Stage33: actual pure Stage30 census reused inside bounded transport window.
-- No Roblox runtime, client payloads, or completion authority.
local dir=arg[1] or "pdiddler/new_part4"
package.path=dir.."/?.lua;"..package.path
local M=require("p4_stage33_transport_window")
local C=require("p4_stage30_client_signal_census")
local passed=0
local function check(name,fn)
 local ok,why=pcall(fn)
 if not ok then error("FAILED "..name..": "..tostring(why)) end
 passed=passed+1
end
local function new() return M.new(C,10) end
local function noAuthority(r)
 assert(r.tradeOutcome=="UNKNOWN")
 assert(r.serverAttestation==false and r.serverCompletionProven==false)
 assert(r.causalAttributionProven==false)
 assert(r.authorizesTrade==false and r.authorizesAccept==false)
 assert(r.mayRecordCompletedTrade==false and r.mayReportProfit==false)
 assert(r.readOnly==true)
end
check("uses exactly the Stage30 observed 16 Trade remote names",function()
 local names=M.names()
 assert(#names==16)
 local set={}
 for _,n in ipairs(names) do assert(not set[n]);set[n]=true end
 for _,n in ipairs({"CompleteTrade","EndTrade","DeclineTrade",
  "UpdateOffers","UpdateTrade","StartTrade","AcceptTrade"}) do
  assert(set[n]==true)
 end
end)
check("no trade yet is not a settlement",function()
 local r=M.summary(new())
 assert(r.status=="INCOMPLETE" and r.scopedReceipts==0)
 assert(not r.clientClosureObserved)
 noAuthority(r)
end)
check("pre-open names are not attributed to a transaction",function()
 local s=new()
 assert(M.received(s,"StartTrade",10.1))
 assert(M.received(s,"UpdateTrade",10.2))
 assert(M.open(s,11))
 local r=M.summary(s)
 assert(r.preOpenUnboundCount==2 and r.scopedReceipts==0)
 assert(r.preOpenUnboundNames.StartTrade==1)
 assert(#r.firstReceipts==0)
 noAuthority(r)
end)
check("single open, client receipts and closure grace",function()
 local s=new();assert(M.open(s,11))
 assert(M.received(s,"UpdateOffers",11.5))
 assert(M.received(s,"UpdateTrade",11.7))
 assert(M.close(s,14))
 assert(M.received(s,"CompleteTrade",14.05))
 assert(M.finish(s,16.2,true))
 local r=M.summary(s)
 assert(r.status=="WINDOW_CLOSED_WITH_CLIENT_CENSUS")
 assert(r.scopedReceipts==3 and r.postCloseReceipts==1)
 assert(r.perNameCounts.CompleteTrade==1)
 assert(r.recentReceipts[3].phase=="AFTER_CLOSE")
 assert(#r.firstReceipts==3 and r.catalogSize==16)
 noAuthority(r)
end)
check("successful-looking CompleteTrade still cannot authorize",function()
 local s=new();M.open(s,11)
 M.received(s,"AcceptTrade",11.2)
 M.close(s,12)
 M.received(s,"CompleteTrade",12.2)
 M.finish(s,14.3,true)
 noAuthority(M.summary(s))
end)
check("decline name cannot prove an initiator or failed exchange",function()
 local s=new();M.open(s,11)
 M.received(s,"DeclineTrade",12)
 M.close(s,13)
 M.finish(s,15.3,true)
 assert(M.summary(s).perNameCounts.DeclineTrade==1)
 noAuthority(M.summary(s))
end)
check("first 24 may truncate but final 16 retain late result names",function()
 local s=new();M.open(s,11)
 for i=1,60 do assert(M.received(s,"UpdateOffers",11+i/100)) end
 assert(M.close(s,13))
 assert(M.received(s,"EndTrade",13.1))
 assert(M.finish(s,15.2,true))
 local r=M.summary(s)
 assert(r.scopedReceipts==61 and r.perNameCounts.UpdateOffers==60)
 assert(r.retainedFirstReceipts==24 and r.earlierReceiptsTruncated)
 assert(r.firstReceipts[24].name=="UpdateOffers")
 assert(r.recentReceipts[#r.recentReceipts].name=="EndTrade")
 assert(r.postCloseReceipts==1)
 noAuthority(r)
end)
check("strict tail window never grows beyond sixteen",function()
 local s=new();M.open(s,11)
 for i=1,95 do M.received(s,"UpdateTrade",11+i/1000) end
 local r=M.summary(s)
 assert(r.retainedRecentReceipts==16 and #r.recentReceipts==16)
 assert(r.perNameCounts.UpdateTrade==95)
end)
check("unknown name never appears in census or pre-counts",function()
 local s=new()
 assert(not M.received(s,"OutsideFolder",10.1))
 M.open(s,11)
 assert(not M.received(s,"Player_12345",11.1))
 local r=M.summary(s)
 assert(r.preOpenUnboundCount==0 and r.scopedReceipts==0)
 assert(r.perNameCounts.Player_12345==nil)
end)
check("double open cannot create duplicate session",function()
 local s=new();assert(M.open(s,11))
 assert(not M.open(s,11.1))
 assert(s.phase=="ACTIVE" and s.census.listeners==16)
end)
check("double close cannot issue duplicate completion",function()
 local s=new();M.open(s,11)
 assert(M.close(s,12))
 assert(not M.close(s,12.1))
 M.finish(s,14.1,true)
 assert(not M.finish(s,15.2,true))
 noAuthority(M.summary(s))
end)
check("early finish fails closed and forbids completion claims",function()
 local s=new();M.open(s,11)
 M.close(s,12)
 assert(M.finish(s,12.2,true))
 assert(M.summary(s).status=="INCOMPLETE")
 noAuthority(M.summary(s))
end)
check("timeout with no GUI fails closed",function()
 local s=new();assert(M.finish(s,120,false))
 assert(M.summary(s).status=="INCOMPLETE")
 assert(not M.received(s,"StartTrade",121))
end)
check("aborted active window fails closed",function()
 local s=new();M.open(s,11)
 M.received(s,"UpdateOffers",12)
 M.finish(s,13,false)
 assert(M.summary(s).status=="INCOMPLETE")
 noAuthority(M.summary(s))
end)
check("non-finite and backward times rejected",function()
 local s=new()
 assert(not M.open(s,9))
 assert(not M.received(s,"StartTrade",0/0))
 M.open(s,11)
 assert(not M.close(s,9))
 assert(not M.received(s,"UpdateOffers",10.1))
end)
check("no result leaks account IDs, job IDs, fingerprints or payload",function()
 local s=new();M.received(s,"StartTrade",10.4)
 M.open(s,11);M.received(s,"UpdateOffers",12)
 M.close(s,13);M.finish(s,15.4,true)
 local r=M.summary(s)
 for _,key in ipairs({"accountId","playerId","partnerId","jobId",
  "session","rawArgs","itemId","fingerprint","profit"}) do
  assert(r[key]==nil)
 end
 noAuthority(r)
end)
check("first native Stage33 StartTrade then UpdateTrade and two AcceptTrade stays unknown",function()
 -- Grounded in the first actual iPad Stage33 anonymized JSON.
 -- StartTrade receipt arrived before GUI window was bound; no attribution.
 -- The exact inbound times are local elapsed client clocks, not server IDs.
 local s=new()
 assert(M.received(s,"StartTrade",10.4)=="PRE_OPEN_UNBOUND")
 assert(M.open(s,11))
 assert(M.received(s,"UpdateTrade",20.039))
 assert(M.received(s,"AcceptTrade",27.736))
 assert(M.received(s,"AcceptTrade",28.989))
 assert(M.close(s,29.3))
 assert(M.finish(s,31.8,true))
 local r=M.summary(s)
 assert(r.status=="WINDOW_CLOSED_WITH_CLIENT_CENSUS")
 assert(r.preOpenUnboundCount==1 and r.preOpenUnboundNames.StartTrade==1)
 assert(r.scopedReceipts==3 and r.retainedFirstReceipts==3)
 assert(r.retainedRecentReceipts==3 and not r.earlierReceiptsTruncated)
 assert(r.catalogSize==16 and r.postCloseReceipts==0)
 assert(r.perNameCounts.UpdateTrade==1 and r.perNameCounts.AcceptTrade==2)
 assert(r.perNameCounts.CompleteTrade==nil and
   r.perNameCounts.EndTrade==nil and r.perNameCounts.DeclineTrade==nil)
 assert(r.firstReceipts[1].name=="UpdateTrade"
   and r.firstReceipts[1].phase=="WHILE_OPEN"
   and r.firstReceipts[1].elapsed==9.039)
 assert(r.firstReceipts[2].name=="AcceptTrade"
   and r.firstReceipts[2].elapsed==16.736)
 assert(r.firstReceipts[3].name=="AcceptTrade"
   and r.firstReceipts[3].elapsed==17.989)
 assert(r.recentReceipts[3].name=="AcceptTrade"
   and r.recentReceipts[3].phase=="WHILE_OPEN")
 -- Two named receipts cannot establish actors, both-Accept, or settlement.
 noAuthority(r)
end)
print("PASS",passed,"Stage33 bounded read-only full Trade transport window")
