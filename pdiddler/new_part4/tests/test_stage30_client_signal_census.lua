-- Stage30: pure read-only signal census tests, NO Roblox game calls.
local dir=arg[1] or "pdiddler/new_part4"
package.path=dir.."/?.lua;"..package.path
local M=require("p4_stage30_client_signal_census")
local passed=0
local function check(label,fn)
 local ok,why=pcall(fn)
 if not ok then error("FAILED "..label..": "..tostring(why)) end
 passed=passed+1
end
local function fixture()
 return M.new({session="one-session"},10)
end
check("no source is completion authority",function()
 local r=M.summary(fixture())
 assert(r.tradeOutcome=="UNKNOWN")
 assert(not r.authorizesTrade and not r.authorizesAccept)
 assert(not r.mayRecordCompletedTrade and not r.mayReportProfit)
 assert(not r.serverCompletionProven)
end)
check("catalog only admits bounded native RemoteEvent names",function()
 local s=fixture()
 assert(M.catalog(s,{"CompletedEvent","DeclineTrade","StartTrade"},10))
 local r=M.summary(s)
 assert(r.catalogRemoteEvents==3 and #r.catalogNames==3)
 assert(r.signalReceipts==0)
end)
check("name alone never means completed trade",function()
 local s=fixture();M.catalog(s,{"CompletedEvent"},10)
 assert(M.received(s,"CompletedEvent",12))
 M.closed(s,"CLOSED_UNKNOWN",13)
 M.finish(s,"OBSERVATION_FINISHED",15)
 local r=M.summary(s)
 assert(r.signalReceipts==1)
 assert(r.signals[1].name=="CompletedEvent")
 assert(r.tradeOutcome=="UNKNOWN" and not r.serverCompletionProven)
 assert(not r.mayRecordCompletedTrade)
end)
check("decline-named event receipt is not authoritative decline",function()
 local s=fixture();M.catalog(s,{"DeclineTrade"},10)
 M.received(s,"DeclineTrade",11);M.closed(s,"CLOSED_UNKNOWN",12)
 M.finish(s,"OBSERVATION_FINISHED",14)
 local r=M.summary(s)
 assert(r.tradeOutcome=="UNKNOWN" and r.closureStatus=="CLOSED_UNKNOWN")
end)
check("before/after closure timing is preserved without causal inference",function()
 local s=fixture();M.catalog(s,{"Status","Close"},10)
 M.received(s,"Status",10.5)
 M.closed(s,"CLOSED_UNKNOWN",11)
 M.received(s,"Close",11.1)
 M.finish(s,"OBSERVATION_FINISHED",13)
 local r=M.summary(s)
 assert(r.signals[1].phase=="WHILE_OPEN")
 assert(r.signals[2].phase=="AFTER_CLOSE")
 assert(r.postCloseSignalReceipts==1)
 assert(r.tradeOutcome=="UNKNOWN")
end)
check("same name can repeat but only 24 events retained",function()
 local s=fixture();M.catalog(s,{"UpdateTrade"},10)
 for i=1,100 do assert(M.received(s,"UpdateTrade",10+i/100)) end
 local r=M.summary(s)
 assert(r.signalReceipts==100 and r.retainedReceipts==24)
 assert(#r.signals==24)
 assert(r.catalogRemoteEvents==1)
end)
check("unknown unbound event never becomes a tracked event",function()
 local s=fixture();M.catalog(s,{"TradeStatus"},10)
 assert(not M.received(s,"OtherEvent",12))
 local r=M.summary(s)
 assert(r.signalReceipts==0 and r.ignoredUnboundSignals==1)
end)
check("event names with player-shaped strings are rejected",function()
 local s=fixture();M.catalog(s,{"TradeStatus"},10)
 assert(not M.received(s,"foo/123456/partner",12))
 assert(M.summary(s).signalReceipts==0)
end)
check("catalog rejects duplicate names and excess listeners",function()
 local s=fixture()
 assert(not M.catalog(s,{"Trade","Trade"},10))
 local many={}
 for i=1,33 do many[i]="T"..i end
 assert(not M.catalog(s,many,10))
 assert(M.summary(s).catalogRemoteEvents==0)
end)
check("catalog rejects untrusted names",function()
 local s=fixture()
 assert(not M.catalog(s,{"Trade/Outside"},10))
 assert(not M.catalog(s,{"name with spaces"},10))
 assert(not M.catalog(s,{"Name\nSecret"},10))
end)
check("partner departure is independent of completion or cause of closure",function()
 local s=fixture()
 assert(M.partnerDeparture(s,13))
 M.closed(s,"CLOSED_UNKNOWN",14)
 M.finish(s,"OBSERVATION_FINISHED",16)
 local r=M.summary(s)
 assert(r.partnerDepartureObserved)
 assert(not r.serverCompletionProven)
 assert(r.tradeOutcome=="UNKNOWN")
end)
check("GUI closed without remote signals remains unknown",function()
 local s=fixture()
 M.catalog(s,{},10)
 M.closed(s,"CLOSED_UNKNOWN",11)
 M.finish(s,"OBSERVATION_FINISHED",13)
 local r=M.summary(s)
 assert(r.signalReceipts==0)
 assert(r.status=="CLOSED_WITH_CLIENT_SIGNAL_CENSUS")
 assert(r.tradeOutcome=="UNKNOWN")
end)
check("incomplete session cannot be marked completed",function()
 local s=fixture();M.catalog(s,{},10)
 assert(M.finish(s,"WINDOW_TIMED_OUT",13))
 local r=M.summary(s)
 assert(r.status=="INCOMPLETE")
 assert(not r.mayRecordCompletedTrade)
end)
check("bad close state terminates and cannot reuse session",function()
 local s=fixture()
 assert(not M.closed(s,"SUCCESS",12))
 assert(M.summary(s).status=="INVALID")
 assert(not M.received(s,"TradeStatus",13))
end)
check("duplicate close and finalization cannot double-count",function()
 local s=fixture()
 assert(M.closed(s,"CLOSED_UNKNOWN",11))
 assert(not M.closed(s,"CLOSED_UNKNOWN",12))
 assert(M.finish(s,"OBSERVATION_FINISHED",14))
 assert(not M.finish(s,"OBSERVATION_FINISHED",15))
end)
check("nonmonotonic or invalid receipt times rejected",function()
 local s=fixture();M.catalog(s,{"TradeStatus"},10)
 assert(not M.received(s,"TradeStatus",9))
 assert(not M.received(s,"TradeStatus",0/0))
 assert(M.summary(s).signalReceipts==0)
end)
check("unmodified result contains no players IDs or remote payload",function()
 local s=fixture();M.catalog(s,{"TradeStatus"},10)
 M.received(s,"TradeStatus",10.2)
 M.closed(s,"CLOSED_UNKNOWN",11)
 M.finish(s,"OBSERVATION_FINISHED",13)
 local r=M.summary(s)
 assert(r.session==nil and r.accountId==nil and r.partnerId==nil)
 assert(r.jobId==nil and r.items==nil and r.eventArgs==nil)
end)
print("PASS",passed,"Stage30 read-only client native signal census")
