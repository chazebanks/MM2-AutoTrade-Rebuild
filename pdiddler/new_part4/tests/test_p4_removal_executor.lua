-- Executable Lua 5.4 tests. No Roblox services, no actual clicks.
local root=arg[1] or './'
package.path=root..'/?.lua;'..package.path
local E=require('p4_removal_executor')
local count=0
local function check(name,fn)
    local ok,why=pcall(fn)
    if not ok then error('FAILED '..name..': '..tostring(why)) end
    count=count+1
end
local function eq(x,y) assert(x==y,tostring(x)..' != '..tostring(y)) end
local function row(s,id,qty) return {slot=s,id=id,qty=qty} end
local function observation(s,items,fields)
    local o={tradeOpen=true,session=s.session,contextOK=true,
        ourSig='ours-0',theirSig='them-watergun',ourAccepted=false,theirAccepted=false,
        ownItems=items,ourSlots=#items,theirSlots=1,marketFresh=true,quoteSafe=false}
    for k,v in pairs(fields or {}) do o[k]=v end
    return o
end
local function start(s,rows,sig,now)
    local op,intent=E.prepare(s,'REMOVE_ONE',observation(s,rows,{ourSig=sig}),now)
    eq(op,'DISPATCH')
    eq(E.dispatched(s,intent,{attempted=true,status='SENT_ONCE'},now+.01),'WAIT')
    return intent
end
local m=row(1,'Mortal',1)
local i=row(2,'Immortal',2)
local e=row(3,'EmbersickleChroma',1)
check('no native calls or autoaccept methods exist',function()
    assert(E.accept==nil and E.click==nil and E.insert==nil and E.decline==nil)
end)
check('non-removal directives never mutate state',function()
    local s=E.new('job');eq(E.prepare(s,'REQUEST_PLAN',observation(s,{m}),0),'HOLD');eq(s.mode,'IDLE')
end)
check('highest occupied physical slot deterministically chosen',function()
    local s=E.new('job')
    local a,intent=E.prepare(s,'REMOVE_ONE',observation(s,{i,e,m},{ourSig='raw0'}),0)
    eq(a,'DISPATCH');eq(intent.slot,3);eq(intent.id,'EmbersickleChroma')
end)
check('one command only until independent proof',function()
    local s=E.new('job');local intent=start(s,{m,i,e},'raw-three',0)
    eq(E.prepare(s,'REMOVE_ONE',observation(s,{m,i,e},{ourSig='raw-three'}),.2),'HOLD')
    eq(E.observe(s,observation(s,{m,i,e},{ourSig='raw-three',theirSig='them-empty',theirSlots=0}),.3),'HOLD')
    eq(s.mode,'SENT')
    eq(E.observe(s,observation(s,{m,i},{ourSig='raw-two',theirSig='them-empty',theirSlots=0}),.4),'VERIFIED')
    eq(s.mode,'IDLE');eq(intent.qty,1)
end)
check('stacked two copies removed as one slot',function()
    local s=E.new('job');start(s,{row(1,'Immortal',2)},'stacked',0)
    eq(E.observe(s,observation(s,{}, {ourSig='empty',theirSlots=0}),.15),'VERIFIED')
end)
check('stacked partial decrement requires a new intent',function()
    local s=E.new('job');start(s,{row(1,'Immortal',2)},'stacked',0)
    eq(E.observe(s,observation(s,{row(1,'Immortal',1)},{ourSig='stack-one'}),.15),'VERIFIED')
    local action,intent=E.prepare(s,'REMOVE_ONE',observation(s,{row(1,'Immortal',1)},{ourSig='stack-one'}),.3)
    eq(action,'DISPATCH');eq(intent.qty,1)
end)
check('opponent may swap while own removal is pending',function()
    local s=E.new('job');start(s,{m,i},'raw2',0)
    eq(E.observe(s,observation(s,{m,i},{ourSig='raw2',theirSig='them-sugar'}),.2),'HOLD')
    eq(E.observe(s,observation(s,{m},{ourSig='raw1',theirSig='them-frostsaber'}),.3),'VERIFIED')
end)
check('quantity change without independent GUI signature escalates',function()
    local s=E.new('job');start(s,{m,i},'raw2',0)
    eq(E.observe(s,observation(s,{m},{ourSig='raw2'}),.2),'ESCALATE')
end)
check('raw signature changes without a quantity decrement escalate',function()
    local s=E.new('job');start(s,{m,i},'raw2',0)
    eq(E.observe(s,observation(s,{m,i},{ourSig='raw2-reordered'}),.2),'ESCALATE')
end)
check('unexpected nontarget reduction never counts as acknowledgement',function()
    local s=E.new('job');start(s,{m,i},'raw2',0)
    eq(E.observe(s,observation(s,{i},{ourSig='raw1'}),.2),'ESCALATE')
end)
check('adding a different item after action fails closed',function()
    local s=E.new('job');start(s,{m},'raw1',0)
    eq(E.observe(s,observation(s,{m,row(2,'Laser',1)},{ourSig='raw2'}),.2),'ESCALATE')
end)
check('same item increased is not an acknowledged removal',function()
    local s=E.new('job');start(s,{row(1,'Immortal',2)},'stack2',0)
    eq(E.observe(s,observation(s,{row(1,'Immortal',3)},{ourSig='stack3'}),.2),'ESCALATE')
end)
check('missing native dispatch escalates, never retries',function()
    local s=E.new('job');local a,intent=E.prepare(s,'REMOVE_ONE',observation(s,{m}),0)
    eq(a,'DISPATCH')
    eq(E.dispatched(s,intent,{attempted=false,status='BLOCKED'},.01),'ESCALATE')
    eq(E.prepare(s,'REMOVE_ONE',observation(s,{m}),.2),'ESCALATE')
end)
check('uncertain click is terminal, never retries',function()
    local s=E.new('job');local _,intent=E.prepare(s,'REMOVE_ONE',observation(s,{m}),0)
    eq(E.dispatched(s,intent,{attempted=true,status='ATTEMPT_UNCERTAIN'},.01),'ESCALATE')
end)
check('reservation expires without dispatch',function()
    local s=E.new('job');eq(E.prepare(s,'REMOVE_ONE',observation(s,{m}),0),'DISPATCH')
    eq(E.observe(s,observation(s,{m}),.26),'ESCALATE')
end)
check('no observed removal until proof deadline',function()
    local s=E.new('job',{proofSeconds=1});start(s,{m},'raw1',0)
    eq(E.observe(s,observation(s,{m},{ourSig='raw1'}),.4),'HOLD')
    eq(E.observe(s,observation(s,{m},{ourSig='raw1'}),1.01),'ESCALATE')
end)
check('acceptance during removal is an escalation',function()
    local s=E.new('job');start(s,{m},'raw1',0)
    eq(E.observe(s,observation(s,{m},{ourAccepted=true}),.3),'ESCALATE')
end)
check('partner acceptance during removal is an escalation',function()
    local s=E.new('job');start(s,{m},'raw1',0)
    eq(E.observe(s,observation(s,{m},{theirAccepted=true}),.3),'ESCALATE')
end)
check('unknown acceptance forbids removal',function()
    local s=E.new('job')
    local o=observation(s,{m});o.theirAccepted=nil
    eq(E.prepare(s,'REMOVE_ONE',o,0),'ESCALATE')
end)
check('wrong session stops rather than dispatching',function()
    local s=E.new('job')
    eq(E.prepare(s,'REMOVE_ONE',observation(s,{m},{session='other'}),0),'STOP')
end)
check('closed session stops even when pending',function()
    local s=E.new('job');start(s,{m},'raw1',0)
    eq(E.observe(s,{tradeOpen=false,session='job'},.3),'STOP')
end)
check('opponent signature tamper is rejected in dispatch ledger',function()
    local s=E.new('job')
    local _,intent=E.prepare(s,'REMOVE_ONE',observation(s,{m}),0)
    intent.theirSig='not-the-verified-opponent-quote'
    eq(E.dispatched(s,intent,{status='SENT_ONCE',attempted=true},.01),'ESCALATE')
end)
check('intent identity tamper is rejected',function()
    local s=E.new('job');local _,intent=E.prepare(s,'REMOVE_ONE',observation(s,{m}),0)
    intent.id='Laser';eq(E.dispatched(s,intent,{status='SENT_ONCE',attempted=true},.01),'ESCALATE')
end)
check('cannot reuse same session after stop',function()
    local s=E.new('job');E.stop(s,'manual');eq(E.prepare(s,'REMOVE_ONE',observation(s,{m}),1),'STOP')
end)
check('negative/nonfinite clock never authorizes a click',function()
    local s=E.new('job');eq(E.prepare(s,'REMOVE_ONE',observation(s,{m}),-1),'ESCALATE')
end)
check('multi-slot deterministic removal across 200 synthetic cases',function()
    for trial=1,200 do
        local s=E.new('session-'..trial)
        local items={}
        local n=2+(trial%3)
        for k=1,n do items[k]=row(k,'weapon-'..k,1+(trial+k)%3) end
        local t=0
        while #items>0 do
            local sig='sig-'..#items..'-'..trial
            local _,intent=E.prepare(s,'REMOVE_ONE',observation(s,items,{ourSig=sig}),t)
            assert(intent and intent.slot==#items)
            eq(E.dispatched(s,intent,{status='SENT_ONCE',attempted=true},t+.01),'WAIT')
            items[#items]=nil
            local action=E.observe(s,observation(s,items,{ourSig='sig-'..#items..'-'..trial}),t+.09)
            eq(action,'VERIFIED');t=t+.15
        end
        eq(s.mode,'IDLE')
    end
end)
print('PASS',count,'Stage 10 pure executor tests')
