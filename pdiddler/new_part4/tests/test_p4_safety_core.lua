check('verified withdrawal progress under 200 deterministic slot permutations',function()
    for trial=1,200 do
        local n=1+(trial%4)
        local ours={}
        for j=1,n do ours[j]=item(j,'weapon-'..j,1+(trial+j)%3) end
        local s=S.new('trial-'..trial)
        S.step(s,o(s,ours,'watergun',1,true,{ourSig='initial'}),0)
        equal(select(1,S.step(s,o(s,ours,'empty',0,false,{ourSig='initial'}),.1)),'REMOVE_ONE')
        for remain=n-1,0,-1 do
            local nextRows={}
            -- Reorder the survivors into new slots; identity is the proof, not a slot position.
            for j=1,remain do nextRows[j]=item(j,ours[j].id,ours[j].qty) end
            local action=select(1,S.step(s,o(s,nextRows,'new-quote-'..remain,remain>0 and 1 or 0,false,
                {ourSig='changed-'..remain}),.2+(n-remain)*.12))
            equal(action,remain==0 and 'HOLD' or 'REMOVE_ONE','trial='..trial..' remain='..remain)
        end
        equal(s.mode,'WAIT_REPLAN')
    end
end)


