check('new authorized plan requires exact copies and exact opponent version',function()
    local s=S.new('job-a')
    S.step(s,o(s,{},'empty',0,false,{ourSig='none'}),0)
    S.step(s,o(s,{},'watergun',1,false,{ourSig='none'}),.1)
    equal(select(1,S.step(s,o(s,{},'watergun',1,false,{ourSig='none'}),.8)),'REQUEST_PLAN')
    local accepted,why=S.authorizePlan(s,'watergun',{i,m},.9)
    equal(accepted,true)
    equal(s.mode,'BUILDING')
    equal(select(1,S.step(s,o(s,{m},'watergun',1,false,{ourSig='partial'}),1.0)),'HOLD')
    equal(select(1,S.step(s,o(s,{m,i},'watergun',1,true,{ourSig='complete'}),1.4)),'HOLD')
    equal(s.mode,'MONITOR')
end)
