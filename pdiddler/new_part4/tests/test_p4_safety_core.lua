-- Executable Lua 5.4 test harness for the pure (Luau-compatible) Stage 8 module.
package.path = (arg[1] or './')..'/?.lua;'..package.path
local S = require('p4_safety_core')
local tests = 0
local function equal(a,b,label)
    assert(a == b, (label or 'mismatch')..': expected '..tostring(b)..', got '..tostring(a))
end
local function check(label,fn)
    local ok,err=pcall(fn)
    if not ok then error('TEST '..label..' FAILED: '..tostring(err)) end
    tests=tests+1
end
local function o(s,own,theirSig,theirSlots,safe,props)
    props=props or {}
    local x = {session=s.session,tradeOpen=true,contextOK=true,marketFresh=true,
        ownItems=own,ourSlots=#own,ourSig=props.ourSig or 'our-'..tostring(#own),
        theirSig=theirSig,theirSlots=theirSlots,theirResolved=true,
        quoteSafe=safe,ourAccepted=false,theirAccepted=false}
    for k,v in pairs(props) do x[k]=v end
    return x
end
local function item(slot,id,qty) return {slot=slot,id=id,qty=qty} end
local m=item(1,'Mortal',1)
local i=item(2,'Immortal',2)
local e=item(3,'EmbersickleChroma',1)

check('safe quote does not change',function()
    local s=S.new('job-a')
    local a=o(s,{m,i,e},'watergun',1,true,{ourSig='ours3'})
    equal(select(1,S.step(s,a,0)), 'HOLD')
    equal(select(1,S.step(s,a,.3)), 'HOLD')
    equal(s.mode,'MONITOR')
end)
check('watergun removed: three distinct slots withdraw one by one without decline',function()
    local s=S.new('job-a')
    equal(select(1,S.step(s,o(s,{m,i,e},'watergun',1,true,{ourSig='ours3'}),0)),'HOLD')
    equal(select(1,S.step(s,o(s,{m,i,e},'empty',0,false,{ourSig='ours3'}),.1)),'REMOVE_ONE')
    equal(s.mode,'AWAIT_REMOVAL')
    equal(select(1,S.step(s,o(s,{m,i,e},'empty',0,false,{ourSig='ours3'}),.2)),'HOLD')
    equal(select(1,S.step(s,o(s,{m,i},'empty',0,false,{ourSig='ours2'}),.3)),'REMOVE_ONE')
    equal(select(1,S.step(s,o(s,{i},'other-new',1,false,{ourSig='ours1'}),.6)),'REMOVE_ONE')
    equal(select(1,S.step(s,o(s,{},'other-new',1,false,{ourSig='ours0'}),.8)),'HOLD')
    equal(s.mode,'WAIT_REPLAN')
    equal(select(1,S.step(s,o(s,{},'other-new',1,false,{ourSig='ours0'}),1.5)),'REQUEST_PLAN')
end)
check('stack x2 removed as one slot: verified full quantity reduction',function()
    local s=S.new('job-a')
    S.step(s,o(s,{i},'watergun',1,true,{ourSig='stack2'}),0)
    equal(select(1,S.step(s,o(s,{i},'empty',0,false,{ourSig='stack2'}),.1)),'REMOVE_ONE')
    equal(select(1,S.step(s,o(s,{},'empty',0,false,{ourSig='clear'}),.2)),'HOLD')
    equal(s.mode,'WAIT_REPLAN')
end)
check('stack partial removal is progress, not proof whole slot empty',function()
