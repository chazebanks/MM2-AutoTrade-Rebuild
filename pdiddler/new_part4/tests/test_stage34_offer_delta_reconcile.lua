-- Stage34 actual pure Stage9/29 structural offer-to-owned-delta comparison tests.
-- No Roblox APIs, no OfferItem/Accept/Decline, no completion authority.
local dir=arg[1] or "pdiddler/new_part4"
package.path=dir.."/?.lua;"..package.path
local R=require("p4_stage34_offer_delta_reconcile")
local L=require("p4_stage29_postclose_ledger")
local passed=0
local function test(name,fn)
 local ok,why=pcall(fn)
 if not ok then error("FAILED "..name..": "..tostring(why)) end
 passed=passed+1
end
local function scope()
 return {session="S-34",jobId="one-job",accountId=1,partnerId=2}
end
local function item(id,page,checkerId,qty,slot)
 return {slot=slot or 1,id=id,cat="Weapons",page=page,
   checkerId=checkerId,qty=qty}
end
local alpha=item("Alpha","godly","11",1)
local beta=item("Beta","chroma","12",1)
local function inventory(a,b,extra)
 extra=extra or 0
 local items={}
 if a>0 then items[#items+1]={
  id="Alpha",page="godly",checkerId="11",cat="Weapons",
  type="Knife",qty=a} end
 if b>0 then items[#items+1]={
  id="Beta",page="chroma",checkerId="12",cat="Weapons",
  type="Gun",qty=b} end
 return {items=items,
  fingerprint="alpha:"..a..";beta:"..b..";excluded:"..extra,
  rawOwned=a+b+extra,unmapped=0,badQty=0,unpriced=0}
end
local function native(ours,theirs,signature,accept1,accept2)
 ours=ours or {};theirs=theirs or {}
 local o={tradeOpen=true,contextOK=true,theirResolved=true,
  ourSig="ours:"..(signature or "one"),
  theirSig="theirs:"..(signature or "one"),
  ourSlots=#ours,theirSlots=#theirs,
  ourAccepted=accept1==true,theirAccepted=accept2==true}
 return o,{ourItems=ours,theirItems=theirs}
end
local function observer(sc)
 return R.new(sc,10,{minStableGap=.15,maxCloseLag=.45})
end
local function stable(s,sc,ours,theirs,a1,a2)
 local o,d=native(ours,theirs,"stable",a1,a2)
 assert(R.observe(s,o,d,11,sc)=="OBSERVING")
 assert(R.observe(s,o,d,11.2,sc)=="STABLE")
 assert(R.close(s,11.3,sc)=="CLOSED_UNKNOWN")
end
local function ledger(sc,before,after)
 local l=L.new(sc,10,{maxBeforeToClose=30,minPostGap=.75,maxPostAge=30})
 assert(L.before(l,before,10.1,sc)=="OBSERVED")
 assert(L.close(l,"CLOSED_UNKNOWN",11.3,sc)=="OBSERVED")
 assert(L.after(l,after,12.45,sc,2)=="OBSERVED")
 L.after(l,after,13.55,sc,3)
 return l
end
local function noAuthority(r)
 assert(r.tradeOutcome=="UNKNOWN" and r.causalAttributionProven==false)
 assert(r.serverAttestation==false and r.serverCompletionProven==false)
 assert(r.authorizesAccept==false and r.authorizesTrade==false)
 assert(r.mayRecordCompletedTrade==false and r.mayReportProfit==false)
 assert(r.claimButtonIsNotCreditPrerequisite and r.readOnly)
 assert(r.accountId==nil and r.partnerId==nil and r.jobId==nil)
 assert(r.session==nil and r.items==nil and r.fingerprint==nil)
end
test("one-sided gift exact eligible identity and quantity agree client only",function()
 local sc=scope();local s=observer(sc)
 stable(s,sc,{}, {beta},true,true)
 local r=R.evaluate(s,ledger(sc,inventory(2,1),inventory(2,2)),sc)
 assert(r.status=="OFFER_AND_OWN_DELTA_AGREE_CLIENT_ONLY")
 assert(r.expectedIncomingEligibleCopies==1 and r.expectedOutgoingEligibleCopies==0)
 assert(r.observedIncomingEligibleCopies==1 and r.observedOutgoingEligibleCopies==0)
 assert(r.eligibleIdentityTypesCompared==1 and r.mismatchIdentityTypes==0)
 assert(r.rawWeaponDeltaMatchesExpected and r.stableOfferObserved)
 noAuthority(r)
end)
