#!/usr/bin/env python3
"""Audit original MM2Values source pages and gate research-only observations.

A successful source-page crawl is NOT the publisher's update time and NOT an
authenticated MM2 weapon/checker-ID mapping. Scheduled research publication
requires stable exact item+category coverage and anomaly checks; even published
rows are permanently marked NONAUTHORITATIVE for trading.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
import tempfile
from pathlib import Path
import re
from typing import Any

REPO = Path(__file__).resolve().parents[1]
ROOT = "https://mm2values.com/?p="
KIND_ORDER = ("Godly", "Ancient", "Chroma")
ANCIENT_CHROMAS = frozenset({"Chroma Emberscythe", "Chroma Emberbow"})
MIN_COUNTS = {"Godly": 100, "Ancient": 16, "Chroma": 40}
SKIP = {"Image", "Wiki", "Close", "N/A", "Working on updating images now."}
OLD_ROW = re.compile(
    r'^\s*\["(?P<name>(?:\\.|[^"\\])*)"\]\s*=\s*\{'
    r'value\s*=\s*(?P<value>[0-9]+),\s*category\s*=\s*'
    r'"(?P<category>(?:\\.|[^"\\])*)"\},\s*$'
)


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def decode_lua_quoted(raw: str) -> str:
    # The saved generator escapes only quote and backslash.
    return re.sub(r'\\(["\\])', lambda m: m.group(1), raw)


def read_baseline(path: Path) -> tuple[dict[str, tuple[int, str]], str | None]:
    if not path.is_file():
        raise RuntimeError("saved-baseline-missing")
    text = path.read_text(encoding="utf-8")
    if not text.startswith("-- GENERATED by scripts/update_values.py"):
        raise RuntimeError("baseline-format-unrecognized")
    saved: dict[str, tuple[int, str]] = {}
    in_items = False
    for line in text.splitlines():
        if "items = {" in line:
            if in_items:
                raise RuntimeError("baseline-duplicate-items-table")
            in_items = True
            continue
        if not in_items:
            continue  # Never parse sourceSha256 metadata as weapon rows.
        if line.strip() in ("}", "}}"):
            break
        if line.lstrip().startswith('["'):
            match = OLD_ROW.fullmatch(line)
            if match is None:
                raise RuntimeError("baseline-row-malformed")
            name = decode_lua_quoted(match["name"])
            category = decode_lua_quoted(match["category"])
            value = int(match["value"])
            if not name or value <= 0 or name in saved:
                raise RuntimeError("baseline-duplicate-or-invalid")
            saved[name] = (value, category)
    if not saved:
        raise RuntimeError("baseline-empty")
    header = re.search(r'\bupdated\s*=\s*"([^"]+)"', text)
    # This historical field denotes generated-file date, NOT publisher update.
    return saved, header.group(1) if header else None


def collect(kind: str) -> dict[str, Any]:
    """Fetch ONE original publisher page and preserve raw-response digest."""
    if kind not in KIND_ORDER:
        raise ValueError("unsupported-tier")
    # Keep external dependencies isolated so offline CI can test the actual
    # report/diff implementation without fetching the public Internet.
    import requests
    from bs4 import BeautifulSoup

    url = ROOT + kind.lower()
    response = requests.get(
        url, timeout=35,
        headers={"User-Agent": "MM2AutoTradeValuesAudit/1.0",
                 "Cache-Control": "no-cache"},
    )
    response.raise_for_status()
    raw = response.content
    if not isinstance(raw, bytes) or not 0 < len(raw) <= 4_000_000:
        raise RuntimeError("source-page-empty-or-oversize")
    observed = now_iso()
    soup = BeautifulSoup(raw, "html.parser")
    lines = [text.strip() for text in soup.stripped_strings if text.strip()]
    rows: dict[str, int] = {}
    for i, line in enumerate(lines):
        match = re.fullmatch(r"Value:\s*([\d,]+)", line, re.I)
        if not match:
            continue
        value = int(match.group(1).replace(",", ""))
        if value <= 0 or value > 1_000_000_000:
            raise RuntimeError("source-row-price-invalid")
        name = None
        for candidate in reversed(lines[max(0, i - 7):i]):
            if (candidate not in SKIP
                and not candidate.startswith(("Value:", "Range:", "Demand:",
                                             "Stability:", "TIER", "Sort By:",
                                             "Filter:"))
                and len(candidate) < 90
                and not candidate.startswith("http")):
                name = candidate
                break
        if not name or name in rows:
            raise RuntimeError(f"source-name-missing-or-duplicate:{kind}")
        if kind == "Chroma" and not name.startswith("Chroma "):
            raise RuntimeError("source-chroma-variant-ambiguous")
        rows[name] = value
    if len(rows) < MIN_COUNTS[kind]:
        raise RuntimeError(f"source-minimum-coverage-failed:{kind}")
    return {
        "kind": kind, "url": url, "retrievedAtUtc": observed,
        "sha256": hashlib.sha256(raw).hexdigest(),
        # Held privately until output; never confused with a market quote.
        "sourceHtml": raw,
        "rowCount": len(rows), "rows": rows,
        # Not inferable from the page's HTTP retrieval clock:
        "publisherUpdatedAtUtc": None,
    }


def normalize_page_results(groups: dict[str, dict[str, Any]]) -> dict[str, tuple[int, str]]:
    if set(groups) != set(KIND_ORDER):
        raise RuntimeError("tier-pages-incomplete")
    items: dict[str, tuple[int, str]] = {}
    casefolded: set[str] = set()
    for kind in KIND_ORDER:
        page = groups[kind]
        if page.get("kind") != kind or page.get("url") != ROOT + kind.lower():
            raise RuntimeError("source-tier-url-mismatch")
        if not re.fullmatch(r"[0-9a-f]{64}", str(page.get("sha256", ""))):
            raise RuntimeError("source-page-hash-unverified")
        original_html = page.get("sourceHtml")
        if not isinstance(original_html, bytes) or not 0 < len(original_html) <= 4_000_000:
            raise RuntimeError("source-html-unavailable-or-oversize")
        if hashlib.sha256(original_html).hexdigest() != page["sha256"]:
            raise RuntimeError("source-page-hash-mismatch")
        if page.get("publisherUpdatedAtUtc") is not None:
            raise RuntimeError("unsupported-unverified-publisher-date")
        rows = page.get("rows")
        if not isinstance(rows, dict) or len(rows) < MIN_COUNTS[kind]:
            raise RuntimeError("source-tier-coverage-incomplete")
        if page.get("rowCount") != len(rows):
            raise RuntimeError("source-tier-count-disagrees")
        for name, value in rows.items():
            if not isinstance(name, str) or not name.strip() or type(value) is not int or not 0 < value <= 1_000_000_000:
                raise RuntimeError("source-row-invalid")
            if kind == "Chroma" and not name.startswith("Chroma "):
                raise RuntimeError("source-variant-missing")
            if name in items or name.casefold() in casefolded:
                raise RuntimeError("source-item-appears-across-tiers-or-case-alias")
            casefolded.add(name.casefold())
            category = ("Chroma Ancient" if name in ANCIENT_CHROMAS
                        else "Chroma Godly") if kind == "Chroma" else kind
            items[name] = (value, category)
    return items


def calculate_diff(
    previous: dict[str, tuple[int, str]],
    candidate: dict[str, tuple[int, str]],
) -> dict[str, Any]:
    old_names, new_names = set(previous), set(candidate)
    added = sorted(new_names - old_names)
    removed = sorted(old_names - new_names)
    changed = sorted(name for name in old_names & new_names
                     if previous[name] != candidate[name])
    return {
        "previousRows": len(previous), "candidateRows": len(candidate),
        "added": [{"name": n, "candidate": list(candidate[n])} for n in added],
        "removed": [{"name": n, "previous": list(previous[n])} for n in removed],
        "changed": [{"name": n, "previous": list(previous[n]),
                     "candidate": list(candidate[n])} for n in changed],
        "unchangedRows": len(old_names & new_names) - len(changed),
        "hasDisagreement": bool(added or removed or changed),
    }


def build_report(
    groups: dict[str, dict[str, Any]],
    baseline: dict[str, tuple[int, str]],
    baseline_file_date: str | None,
    audited_at_utc: str,
) -> tuple[dict[str, Any], dict[str, Any]]:
    proposed = normalize_page_results(groups)
    diff = calculate_diff(baseline, proposed)
    evidence = {
        "schema": "gingerscope-stage52-market-source-audit-v1",
        "status": "CANDIDATE_ONLY_NOT_PUBLISHED",
        "auditedAtUtc": audited_at_utc,
        "publisherUpdatedAtUtc": None,   # Unknown; never infer from crawl time.
        "baselineGeneratedDateUnverified": baseline_file_date,
        "source": "https://mm2values.com/",
        "sourcePages": {
            kind: {
                **{key: groups[kind][key]
                   for key in ("url", "retrievedAtUtc", "sha256", "rowCount",
                               "publisherUpdatedAtUtc")},
                "archivedHtml": "source_" + kind.lower() + ".html",
            }
            for kind in KIND_ORDER
        },
        "minimumCountChecksPassed": True,
        "fullCatalogueCompletenessVerified": False,
        "exactMM2WeaponIdentityVerified": False,
        "independentlyVerifiedPublisherDate": False,
        "canPublishPrices": False,
        "liveReady": False,
        "authorizesTrade": False,
        "authorizesAccept": False,
        "mayReportProfit": False,
        "serverCompletionProven": False,
        "diff": diff,
    }
    rows = [{"name": name, "value": value, "category": category}
            for name, (value, category) in sorted(proposed.items())]
    candidate = {
        "schema": "gingerscope-stage52-unreviewed-mm2values-candidate-v1",
        "status": "RESEARCH_ONLY_NO_TRADING_AUTHORITY",
        "publisherUpdatedAtUtc": None,
        "source": evidence["source"],
        "pages": evidence["sourcePages"],
        "rows": rows,
        "rowCount": len(rows),
        "liveReady": False,
        "canPublishPrices": False,
        "authorizesTrade": False,
        "authorizesAccept": False,
    }
    return evidence, candidate


def publish_eligibility(report: dict[str, Any]) -> tuple[bool, str]:
    """Tight source-shape guard, NOT confirmation of economic or ID authority."""
    changes = report["diff"]
    if changes["added"] or changes["removed"]:
        return False, "catalogue-added-or-removed-items-review-required"
    for change in changes["changed"]:
        old_value, old_category = change["previous"]
        new_value, new_category = change["candidate"]
        if old_category != new_category:
            return False, "item-category-or-variant-changed"
        if old_value <= 0 or new_value <= 0:
            return False, "invalid-positive-price-assumption"
        # Research publisher anomaly gate, not a trade profit/loss threshold:
        # block large moves (e.g. a parser shifted a value onto another item).
        if abs(new_value - old_value) > max(30, old_value * 0.30):
            return False, "price-jump-requires-independent-review"
    return True, "STABLE_IDENTITIES_AND_BOUNDED_CHANGES"


def lua_quoted(raw: str) -> str:
    return '"' + raw.replace("\\", "\\\\").replace('"', '\\"') + '"'


def research_lua_source(
    proposed: dict[str, tuple[int, str]],
    report: dict[str, Any],
) -> str:
    # Explicitly avoid the old false claim that crawl day = publisher update.
    now = report["auditedAtUtc"]
    hashes = report["sourcePages"]
    lines = [
        "-- GENERATED by scripts/update_values.py; do not edit manually.",
        "-- RESEARCH-ONLY source observations, NOT current/trade-authorized MM2 quotes.",
        "local M = {",
        ' source = "https://mm2values.com/",',
        ' updated = "PUBLISHER_DATE_UNKNOWN",',
        " retrievedAtUtc = " + lua_quoted(now) + ",",
        " publisherUpdatedAtUtc = nil,",
        ' provenanceScope = "OBSERVED_MM2VALUES_PAGES_NOT_ID_AUTHENTICATED",',
        " complete = false,",
        " liveReady = false,",
        " authorizesTrade = false,",
        " authorizesAccept = false,",
        " mayReportProfit = false,",
        " sourceSha256 = {",
    ]
    for kind in KIND_ORDER:
        lines.append("  [" + lua_quoted(kind) + "] = " +
                     lua_quoted(hashes[kind]["sha256"]) + ",")
    lines.extend([" },", " items = {"])
    for name, (value, category) in sorted(proposed.items()):
        lines.append(
            "  [" + lua_quoted(name) + "] = {value = " + str(value) +
            ", category = " + lua_quoted(category) + "},"
        )
    lines.extend([" }}", "function M.get(name) return M.items[name] end",
                  "return M", ""])
    return "\n".join(lines)


def atomic_replace_text(path: Path, content: str) -> None:
    # Only invoked after source/identity/anomaly gates and an audit artifact.
    tmp_name = None
    try:
        with tempfile.NamedTemporaryFile("w",encoding="utf-8",
                dir=path.parent,prefix=".stage52-",suffix=".tmp",
                delete=False) as tmp:
            tmp.write(content)
            tmp_name = tmp.name
        os.replace(tmp_name, path)
    finally:
        if tmp_name is not None and os.path.exists(tmp_name):
            os.unlink(tmp_name)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    modes=parser.add_mutually_exclusive_group()
    modes.add_argument("--audit-only",action="store_true",
                       help="Fetch/compare/archive only; never write source values")
    modes.add_argument("--publish-research-only",action="store_true",
                       help="Publish only if same exact item set/categories and bounded values; never trade authoritative")
    parser.add_argument("--output-dir", type=Path,
                        default=REPO / ".market_refresh_audits")
    parser.add_argument("--baseline", type=Path,
                        default=REPO / "values/mm2values.lua")
    args = parser.parse_args(argv)
    previous, original_generated_date = read_baseline(args.baseline)
    # Read AND validate all three pages before creating any artifacts.
    groups = {kind: collect(kind) for kind in KIND_ORDER}
    report, candidate = build_report(groups, previous,
                                     original_generated_date, now_iso())
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "source_audit.json").write_text(
        json.dumps(report, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    (args.output_dir / "candidate_NOT_FOR_TRADING.json").write_text(
        json.dumps(candidate, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    # Preserve the exact three original HTTP response bodies that each SHA
    # describes. Neither a URL nor a digest alone is a reproducible capture.
    for kind in KIND_ORDER:
        source_file = report["sourcePages"][kind]["archivedHtml"]
        (args.output_dir / source_file).write_bytes(groups[kind]["sourceHtml"])
    if args.publish_research_only:
        permitted,why=publish_eligibility(report)
        if not permitted:
            print("REVIEW_REQUIRED:",why,"candidate saved but source values unchanged")
            return 2
        fresh=research_lua_source(normalize_page_results(groups),report)
        current_text=args.baseline.read_text(encoding="utf-8")
        # No re-dating on a day with identical values and existing research
        # metadata. An old legacy file is migrated once to explicit unknown.
        if report["diff"]["hasDisagreement"] or "PUBLISHER_DATE_UNKNOWN" not in current_text:
            atomic_replace_text(args.baseline,fresh)
            print("RESEARCH_SOURCE_UPDATED",
                  "rows",candidate["rowCount"],
                  "changes",len(report["diff"]["changed"]),
                  "publisher-date UNKNOWN; trade authority FALSE")
        else:
            print("RESEARCH_SOURCE_UNCHANGED: no price movement; date NOT advanced")
    else:
        print("AUDIT_ONLY",
              "rows", candidate["rowCount"],
              "changed", len(report["diff"]["changed"]),
              "added", len(report["diff"]["added"]),
              "removed", len(report["diff"]["removed"]),
              "publisher-date UNKNOWN; not published")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
