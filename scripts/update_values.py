#!/usr/bin/env python3
"""Refresh the complete MM2Values Godly/Ancient/Chroma snapshot.
Requires: pip install requests beautifulsoup4
Fails closed: never replaces the saved database with a partial scrape.
"""
import datetime, pathlib, re, requests
from bs4 import BeautifulSoup

ROOT = "https://mm2values.com/?p="
ANCIENT_CHROMAS = {"Chroma Emberscythe", "Chroma Emberbow"}
MIN_COUNTS = {"Godly": 100, "Ancient": 16, "Chroma": 40}
SKIP = {"Image", "Wiki", "Close", "N/A", "Working on updating images now."}

def collect(kind):
    response = requests.get(ROOT + kind.lower(), timeout=35, headers={"User-Agent":"MM2AutoTradeValues/1.0"})
    response.raise_for_status()
    soup = BeautifulSoup(response.text, "html.parser")
    lines = [s.strip() for s in soup.stripped_strings if s.strip()]
    rows = {}
    for i, line in enumerate(lines):
        m = re.fullmatch(r"Value:\s*([\d,]+)", line, re.I)
        if not m:
            continue
        value = int(m.group(1).replace(",", ""))
        if value <= 0:
            continue
        name = None
        for candidate in reversed(lines[max(0, i-7):i]):
            if (candidate not in SKIP and not candidate.startswith(("Value:", "Range:", "Demand:", "Stability:", "TIER", "Sort By:", "Filter:"))
                and len(candidate) < 90 and not candidate.startswith("http")):
                name = candidate
                break
        if not name or name in rows:
            raise RuntimeError(f"Missing/duplicate name in {kind}: {name!r}")
        if kind == "Chroma" and not name.startswith("Chroma "):
            raise RuntimeError(f"Unexpected Chroma name: {name}")
        rows[name] = value
    if len(rows) < MIN_COUNTS[kind]:
        raise RuntimeError(f"Incomplete {kind}: {len(rows)} < {MIN_COUNTS[kind]}")
    return rows

def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    groups = {kind: collect(kind) for kind in ("Godly", "Ancient", "Chroma")}
    items = {}
    for kind, rows in groups.items():
        for name, value in rows.items():
            category = ("Chroma Ancient" if name in ANCIENT_CHROMAS else "Chroma Godly") if kind == "Chroma" else kind
            if name in items:
                raise RuntimeError("Duplicate across categories: " + name)
            items[name] = (value, category)
    today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    lines = [
        "-- GENERATED by scripts/update_values.py; do not edit manually.",
        "-- Primary source: https://mm2values.com/ (Godly, Ancient, Chromas)",
        "local M = {source = \"https://mm2values.com/\", updated = " + lua_string(today) + ", complete = true, items = {",
    ]
    for name, (value, category) in sorted(items.items()):
        lines.append("  [" + lua_string(name) + "] = {value = " + str(value) + ", category = " + lua_string(category) + "},")
    lines += ["}}", "function M.get(name) return M.items[name] end", "return M", ""]
    path = pathlib.Path("values/mm2values.lua")
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print("Saved", len(items), "items", {k: len(v) for k,v in groups.items()})

if __name__ == "__main__":
    main()
