"""Stage68: in-memory SHADOW idempotence for CLIENT run IDs, not MM2 trades.

A GUID generated by the local client prevents repeated copies of the same
observer report being treated as distinct client observations. It cannot
authenticate an MM2 settlement, prove completed/rejected trades, safely
train a market learner, or distinguish malicious re-issued fake GUIDs.
No persistence, Discord calls, network calls or mutable external services.
"""
from __future__ import annotations

import re

CLIENT_SCHEMA = "gingerscope-stage68-client-run-id-observation-v1"
GUID = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"
)
FIXED_FALSE = (
    "serverCompletionProven", "serverAttestation",
    "serverTransactionIdAuthenticated", "eventSessionAssociationProven",
    "causalTradeAttributionProven", "exactWeaponIdentityConfirmed",
    "mayRecordCompletedTrade", "mayRecordRejectedTrade",
    "mayReportProfit", "mayUseForStrategyLearning",
    "authorizesAccept", "authorizesTrade",
    "clientReciprocalTransferProven", "clientRunNonceProvenServerSide",
)
REQUIRED_TRUE = (
    "readOnly", "privateRawKeyEqualityObserved",
    "privateRawDataReleased", "listenerDisconnected",
)
def _out(status: str, reason: str, observed_count: int) -> dict:
    return {
        "schema": "gingerscope-stage68-shadow-observation-ledger-v1",
        "status": status,
        "reason": reason,
        "shadowClientObservationCount": observed_count,
        "distinctTradeCount": 0,
        "completedTradesRecorded": 0,
        "rejectedTradesRecorded": 0,
        "profitClaimsRecorded": 0,
        "marketTrainingExamples": 0,
        "authenticatedServerTransactions": 0,
        "observationNonceIsServerAuthenticated": False,
        "tradeOutcome": "UNKNOWN",
        "mayRecordCompletedTrade": False,
        "mayRecordRejectedTrade": False,
        "mayUseForStrategyLearning": False,
        "mayReportProfit": False,
        "authorizesAccept": False,
        "discordWebhookSent": False,
    }

class ShadowLedger:
    """Short-lived, in-memory nonce set. NOT a persisted database or learner."""
    def __init__(self):
        self._seen: set[str] = set()

    @property
    def client_observation_count(self) -> int:
        return len(self._seen)

    def ingest(self, report: object) -> dict:
        if not isinstance(report, dict):
            return _out("QUARANTINED", "SOURCE_NOT_A_SINGLE_REPORT", len(self._seen))
        nonce = report.get("clientRunNonce")
        if (report.get("schema") != CLIENT_SCHEMA
                or type(nonce) is not str
                or GUID.fullmatch(nonce) is None
                or report.get("status")
                != "CLIENT_RAW_RECEIPT_EQUALS_OWN_GAIN_UNATTRIBUTED"
                or report.get("tradeOutcome") != "UNKNOWN"):
            return _out("QUARANTINED", "RUN_ID_OR_SOURCE_STATUS_UNTRUSTED", len(self._seen))
        if any(report.get(k) is not False for k in FIXED_FALSE):
            return _out("QUARANTINED", "FORGED_AUTHORITY_FLAG", len(self._seen))
        if any(report.get(k) is not True for k in REQUIRED_TRUE):
            return _out("QUARANTINED", "RELEASE_OR_LOCAL_EVIDENCE_INCOMPLETE", len(self._seen))
        if (report.get("privateRawEqualityStatus")
                != "PRIVATE_RAW_PRIMITIVE_EQUALITY_CLIENT_ONLY"):
            return _out("QUARANTINED", "PRIVATE_RAW_CLIENT_EQUALITY_NOT_PROVEN", len(self._seen))
        # A report's local GUID is an idempotence key only.
        if nonce in self._seen:
            return _out("DUPLICATE_CLIENT_RUN", "REPLAY_OF_EXISTING_CLIENT_OBSERVATION",
                        len(self._seen))
        self._seen.add(nonce)
        return _out("SHADOW_CLIENT_OBSERVATION_ONLY",
                    "source-client-run-accepted-for-nonlearning-idempotence",
                    len(self._seen))
